export function text(key, language = 'ko', values = {}) {
  if (!messages[key]) throw new Error(`Unknown translation: ${key}`);
  if (language === 'en' && key === 'pathSummary') {
    return `${values.edges} ${values.edges === 1 ? 'connection' : 'connections'} · ${values.groups} ${values.groups === 1 ? 'group' : 'groups'}`;
  }
  if (language === 'en' && values.count === 1) {
    const singular = { groupCount: '1 group', searchCount: '1 result', searchConnections: '1 connection' };
    if (singular[key]) return singular[key];
  }
  return messages[key][language === 'en' ? 1 : 0].replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}
