export const languages = ['ko', 'en'];
export const languageOf = (path = '/') => /^\/en(?:\/|$)/.test(path) ? 'en' : 'ko';
export function localizedPath(path, language = 'ko') {
  const base = path.replace(/^\/en(?=\/|$)/, '') || '/';
  return language === 'en' ? `/en${base}` : base;
}

